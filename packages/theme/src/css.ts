/**
 * One generator, two sinks: this file is the CSS one. Every value is re-serialised from the
 * generator's own numbers — no input string is ever passed through (28 §4.4 O).
 *
 * The output is four blocks of custom properties in `@layer theme`, which sits BEFORE `@layer a11y`.
 * That ordering is the mechanical form of "a theme is data, not authority": a theme cannot remove
 * the focus ring, the forced-colors overrides or the target floor, because they are in a later layer.
 */

import type { Built, Palette, Scheme } from './build.ts';

const decls = (p: Palette, indent: string): string =>
  Object.entries(p)
    .map(([role, value]) => `${indent}--${role}: ${value};`)
    .join('\n');

function block(built: Built, scheme: Scheme, selector: string, indent = '  '): string {
  const inner = indent + '  ';
  const e = built.elevation[scheme];
  const m = built.mark[scheme];
  return [
    `${indent}${selector} {`,
    decls(built.schemes[scheme], inner),
    `${inner}--mark-l: ${m.L};`,
    `${inner}--mark-c: ${m.C};`,
    /* The row washes and the arrival tint. Generated values that are not roles, emitted where the palette is so
       they swap with the scheme and with high contrast in the same block. */
    ...Object.entries(built.chrome[scheme]).map(([k, v]) => `${inner}--${k}: ${v};`),
    `${inner}--e1: ${e[0]};`,
    `${inner}--e2: ${e[1]};`,
    `${inner}--e3: ${e[2]};`,
    `${indent}}`,
  ].join('\n');
}

/**
 * Four blocks per theme: the base (light), the dark swap for a reader who chose nothing, and the
 * two explicit choices. Base rules first, always — a rule inside `@media` loses to an identical
 * bare selector written below it, and that bug shipped eight times in the predecessor (22 §7).
 */
function schemeBlocks(built: Built, root: string, indent = '  '): string {
  const q = (sel: string) => `${root}${sel}`;
  return [
    block(built, 'light', q(''), indent),
    `${indent}@media (prefers-color-scheme: dark) {`,
    block(built, 'dark', q(':not([data-scheme])'), indent + '  '),
    `${indent}}`,
    block(built, 'light', q("[data-scheme='light']"), indent),
    block(built, 'dark', q("[data-scheme='dark']"), indent),
  ].join('\n');
}

export function toCSS(house: Built, highContrast: Built): string {
  return [
    // Pure ASCII on purpose: this file is compared byte for byte in CI, and an em dash is one more
    // thing that can differ between a checkout and a generator.
    '/* GENERATED by packages/theme. Do not edit - edit the seed and rebuild. */',
    '@layer theme {',
    schemeBlocks(house, 'html'),
    '',
    '  /* prefers-contrast: more swaps the whole palette. On Windows a Contrast Theme reports it',
    '     from the actual ratio; on macOS "Increase Contrast" reports it with no forced colours. */',
    '  @media (prefers-contrast: more) {',
    schemeBlocks(highContrast, 'html', '    '),
    '  }',
    schemeBlocks(highContrast, "html[data-theme='hc']"),
    '}',
    '',
  ].join('\n');
}

/**
 * Check L's other half. Under `forced-colors: active` the UA overrides every colour property and
 * `box-shadow` computes to `none` — so the five-surface ladder becomes one surface and every block
 * boundary in the product disappears. The ladder cannot rescue it, because the shadows are gone too.
 * Lives in `@layer a11y`, which no theme can reach.
 */
export const forcedColors = (classes: readonly string[]): string => `@media (forced-colors: active) {
    ${[...new Set([...classes, 'block'])].map((c) => `.${c}`).join(', ')} {
      border: 1px solid CanvasText;
    }
    [data-intent] { forced-color-adjust: none; }
    :focus-visible { outline: 2px solid Highlight; outline-offset: 2px; }
  }`;

/**
 * `--brand`, emitted into the generated stylesheet rather than typed into `tokens.css`.
 *
 * THE LOGO IS NOT THE ACCENT, AND IT USED TO BE THE SAME LITERAL WRITTEN TWICE. `tokens.css` carried
 * `--brand: #cf413a;` by hand, beside a comment explaining that it is deliberately the same value
 * the generator seeds `--accent` from — two copies of one colour, one of them outside the generator,
 * and `colour-grep`'s only `ALLOWED_LINES` exemption existed to let it past.
 *
 * The cost of the copy is not tidiness. `tokens.css` is shared by both apps and every deployment, so
 * a alpha build would have worn the production mark whatever its accent did — the one place where
 * telling the environments apart matters most, wearing the wrong one by construction.
 *
 * IT IS NOT PART OF `toCSS`, AND THAT IS THE POINT. `toCSS` emits what a THEME may set, and a theme
 * a customer installs must not be able to repaint the logo: `04 §7` and `28 §4.5` both put the mark
 * outside the palette a pack may touch. So the mark is emitted alongside, by the build, from a value
 * the build chooses — and a record's theme has no way to reach it.
 *
 * `@layer theme` so it sits with the rest of the generated block and a `tokens.css` rule can still
 * override it locally without a specificity fight.
 */
export const brand = (colour: string): string =>
  ['', '@layer theme {', '  html {', `    --brand: ${colour.toLowerCase()};`, '  }', '}', ''].join('\n');

/**
 * THE AGENTS' OWN COLOURS, for the two marks their makers draw in colour (`apps/web/src/lib/ui/agent-marks.ts`): Claude's
 * clay and Gemini's blue. The owner asked for the agents' real marks (30 September 2026), and a real mark wears its
 * maker's colour. Emitted beside `--brand` and outside `toCSS` for the same reason the mark is: they are nobody's to
 * theme, and a record's palette must not be able to repaint somebody else's logo. Both read on either scheme's ground.
 */
export const AGENT_COLOURS = { claude: '#d97757', gemini: '#3186ff' } as const;

export const agentColours = (): string =>
  ['', '@layer theme {', '  html {', ...Object.entries(AGENT_COLOURS).map(([k, v]) => `    --agent-${k}: ${v};`), '  }', '}', ''].join('\n');
