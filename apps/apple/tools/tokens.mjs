/**
 * The apps' colours, from the one place colour comes from: `packages/theme`, `HOUSE.frame`, the same role tokens the web
 * paints with (`--board`, `--tile`, `--ink-3`, `--red-fill`, ...).
 *
 *   node apps/apple/tools/tokens.mjs           write them
 *   node apps/apple/tools/tokens.mjs --check   fail if a written file is not what the theme makes now
 *
 * WHAT IT WRITES. One colour set per role, with a light and a dark value, into the kit's asset catalog
 * (`Packages/BrainDogKit/Sources/BrainDogKit/Resources/Colours.xcassets`), so SwiftUI, UIKit and AppKit all resolve the
 * scheme themselves; `Tokens.generated.swift`, which names each set as a `Color` and a platform colour, so a view writes
 * `Palette.ink3` and never a hex; and the app's own catalog's launch ground and accent, which an Info.plist and the
 * launch screen read by name.
 *
 * NEVER BY HAND, AS THE COLOUR GREP DEMANDS OF THE WEB. A hex in a Swift file is a colour nobody validated: the theme's
 * checks hold every pair in `FRAME_PAIRS` to its floor, and these are those values, byte for byte. A palette change is
 * this script run again, and `--check` says when it was not.
 */

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { argv, exit } from 'node:process';

import { CATS, FRAME_ROLES, HOUSE } from '../../../packages/theme/src/index.ts';

const apple = join(import.meta.dirname, '..');
const kit = join(apple, 'Packages', 'BrainDogKit', 'Sources', 'BrainDogKit');
const catalog = join(kit, 'Resources', 'Colours.xcassets');
const app = join(apple, 'Assets.xcassets');

/** Every role the stylesheet paints with, and the scrim, the one value with an alpha. */
const ROLES = [...FRAME_ROLES, 'scrim'];

/** `--tile-2` is `tile2` in Swift, `--cat-blue-tint` is `catBlueTint`. */
const swiftName = (role) => role.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

/** `#RRGGBB` or `rgb(r g b / a)` as the four components a colour set holds, each 0 to 1 with three places. */
function components(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) {
    const n = parseInt(hex[1], 16);
    return { red: (n >> 16) & 255, green: (n >> 8) & 255, blue: n & 255, alpha: 1 };
  }
  const rgb = /^rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*\/\s*([\d.]+)\s*\)$/.exec(value);
  if (rgb) return { red: Number(rgb[1]), green: Number(rgb[2]), blue: Number(rgb[3]), alpha: Number(rgb[4]) };
  throw new Error(`The theme gave ${JSON.stringify(value)}, which is neither #RRGGBB nor rgb(r g b / a); the apps read only those.`);
}

const colour = (value) => {
  const c = components(value);
  const byte = (n) => `0x${n.toString(16).toUpperCase().padStart(2, '0')}`;
  return { 'color-space': 'srgb', components: { red: byte(c.red), green: byte(c.green), blue: byte(c.blue), alpha: c.alpha.toFixed(3) } };
};

const json = (o) => `${JSON.stringify(o, null, 2)}\n`;

/** One colour set: the light value for any appearance, the dark one for dark. */
const colourSet = (light, dark) =>
  json({
    colors: [
      { idiom: 'universal', color: colour(light) },
      { idiom: 'universal', appearances: [{ appearance: 'luminosity', value: 'dark' }], color: colour(dark) },
    ],
    info: { author: 'xcode', version: 1 },
  });

const frame = HOUSE.frame;

/** Every file this writes, by path, with its text. */
function outputs() {
  const out = new Map();
  out.set(join(catalog, 'Contents.json'), json({ info: { author: 'xcode', version: 1 } }));
  for (const role of ROLES) out.set(join(catalog, `${role}.colorset`, 'Contents.json'), colourSet(frame.light[role], frame.dark[role]));

  /* THE APP'S OWN CATALOG: the launch screen's ground (the board) and the accent a system control borrows (the red as
     words, which is what a tinted link or a text cursor is). The app icon lives beside them (`app-icon.mjs`). */
  out.set(join(app, 'Contents.json'), json({ info: { author: 'xcode', version: 1 } }));
  out.set(join(app, 'LaunchGround.colorset', 'Contents.json'), colourSet(frame.light.board, frame.dark.board));
  out.set(join(app, 'AccentColor.colorset', 'Contents.json'), colourSet(frame.light.red, frame.dark.red));

  const lines = ROLES.map((role) => {
    const name = swiftName(role);
    return [
      `    /// \`--${role}\`: ${frame.light[role]} light, ${frame.dark[role]} dark.`,
      `    public static let ${name} = Color("${role}", bundle: .module)`,
    ].join('\n');
  });
  const platform = ROLES.map((role) => `    public static var ${swiftName(role)}: PlatformColor { named("${role}") }`);
  out.set(
    join(kit, 'Look', 'Tokens.generated.swift'),
    `// GENERATED by apps/apple/tools/tokens.mjs from packages/theme (HOUSE.frame). Do not edit: run the script again.
//
// Every colour a native screen paints with, by the web's own role name. A view never writes a hex value.

import SwiftUI
#if canImport(UIKit)
import UIKit
public typealias PlatformColor = UIColor
#else
import AppKit
public typealias PlatformColor = NSColor
#endif

/// The house palette's roles as SwiftUI colours. Each resolves light or dark by itself.
public enum Palette {
${lines.join('\n')}

    /// The eight category hues, in the theme's order, for a project's or a list's mark.
    public static let categories: [Color] = [${CATS.map((c) => swiftName(`cat-${c}`)).join(', ')}]
    /// Their tints, in the same order.
    public static let categoryTints: [Color] = [${CATS.map((c) => swiftName(`cat-${c}-tint`)).join(', ')}]
}

/// The same roles as UIKit / AppKit colours, for a navigation bar's appearance or a web view's ground.
public enum PlatformPalette {
${platform.join('\n')}

    private static func named(_ name: String) -> PlatformColor {
        #if canImport(UIKit)
        return UIColor(named: name, in: .module, compatibleWith: nil) ?? .clear
        #else
        return NSColor(named: name, bundle: .module) ?? .clear
        #endif
    }
}
`,
  );
  return out;
}

async function read(path) {
  try {
    return await readFile(path, 'utf8');
  } catch {
    return null;
  }
}

const wanted = outputs();
if (argv.includes('--check')) {
  const stale = [];
  for (const [path, text] of wanted) if ((await read(path)) !== text) stale.push(path);
  if (stale.length > 0) {
    console.error(`These are not what packages/theme makes now; run node apps/apple/tools/tokens.mjs:\n${stale.map((p) => `  ${p}`).join('\n')}`);
    exit(1);
  }
  console.log(`${wanted.size} colour files match the theme.`);
} else {
  /* A ROLE THE THEME NO LONGER HAS IS A SET NOBODY VALIDATES, so the kit's catalog is written whole. */
  const kept = new Set([...wanted.keys()].filter((p) => p.startsWith(catalog)).map((p) => dirname(p)));
  for (const entry of await readdir(catalog).catch(() => [])) {
    const at = join(catalog, entry);
    if (entry.endsWith('.colorset') && !kept.has(at)) await rm(at, { recursive: true });
  }
  for (const [path, text] of wanted) {
    await mkdir(dirname(path), { recursive: true });
    if ((await read(path)) !== text) await writeFile(path, text);
  }
  console.log(`wrote ${ROLES.length} colour sets and Tokens.generated.swift from HOUSE.frame`);
}
