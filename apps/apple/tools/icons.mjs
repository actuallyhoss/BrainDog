/**
 * The apps' glyphs, from the web's own set: `apps/web/src/lib/ui/icons.ts` (`PATHS`, then `HAND`), each written as a
 * template SVG image set in the kit's `Icons.xcassets`.
 *
 *   node apps/apple/tools/icons.mjs           write them
 *   node apps/apple/tools/icons.mjs --check   fail if a written set is not what the web's glyphs make now
 *
 * THE WEB'S HAND, NOT SF SYMBOLS (plan 3.5). A tab, a well or a row in a native screen draws the same 24-grid shape at
 * the same 1.75 stroke the web draws, so a screen that is half native and half web reads as one product. Each is a
 * TEMPLATE image, so it takes the colour of the text it sits in (`foregroundStyle(Palette.ink3)`) and never carries one.
 *
 * READ AS TEXT, AS `braindog-render`'s own glyph test reads it: icons.ts promises one entry per line, `name: '<markup>'`,
 * between the object's braces, and importing it would pull the renderer's set in for nothing.
 *
 * `glyph.tab` IS THE SAME SHAPE AT 1.5, for a tab bar, where iOS draws an image at 25 points and the web's 1.75 at that
 * size reads a hair heavier than the system's own tab glyphs beside it.
 */

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { argv, exit } from 'node:process';

import { MARK } from '../../../packages/skin/mark.ts';

const apple = join(import.meta.dirname, '..');
const root = join(apple, '..', '..');
const source = join(root, 'apps', 'web', 'src', 'lib', 'ui', 'icons.ts');
const catalog = join(apple, 'Packages', 'BrainDogKit', 'Sources', 'BrainDogKit', 'Resources', 'Icons.xcassets');

/** The entries of one `export const NAME = { ... }` block, as name and inner markup. */
function entries(text, block) {
  const start = text.indexOf(`export const ${block} = {`);
  if (start < 0) throw new Error(`icons.ts has no ${block}; the apps' glyphs are read from it.`);
  const end = text.indexOf('\n}', start);
  const out = [];
  for (const line of text.slice(start, end).split('\n')) {
    const m = /^\s*'?([A-Za-z][A-Za-z0-9-]*)'?:\s*'(.*)',\s*$/.exec(line);
    if (m) out.push([m[1], m[2]]);
  }
  if (out.length === 0) throw new Error(`icons.ts's ${block} had no entry this could read.`);
  return out;
}

/** The glyph as a 24-point SVG: stroked, round, in black, which a template image reads only as coverage. */
const svg = (markup, stroke) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000000" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">${markup}</svg>\n`;

const json = (o) => `${JSON.stringify(o, null, 2)}\n`;

const imageSet = (file) =>
  json({
    images: [{ filename: file, idiom: 'universal' }],
    info: { author: 'xcode', version: 1 },
    properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
  });

/** `chevronDown` is `glyph.chevron-down`, `user-check` stays as it is. */
const assetName = (name) => `glyph.${name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;

async function outputs() {
  const text = await readFile(source, 'utf8');
  const glyphs = [...entries(text, 'PATHS'), ...entries(text, 'HAND')];
  const out = new Map();
  out.set(join(catalog, 'Contents.json'), json({ info: { author: 'xcode', version: 1 } }));
  for (const [name, markup] of glyphs) {
    const asset = assetName(name);
    out.set(join(catalog, `${asset}.imageset`, `${asset}.svg`), svg(markup, 1.75));
    out.set(join(catalog, `${asset}.imageset`, 'Contents.json'), imageSet(`${asset}.svg`));
    const tab = `${asset}.tab`;
    out.set(join(catalog, `${tab}.imageset`, `${tab}.svg`), svg(markup, 1.5));
    out.set(join(catalog, `${tab}.imageset`, 'Contents.json'), imageSet(`${tab}.svg`));
  }

  /* AND THE MARK, as a template too, so Sign in draws it in `Palette.redFill` and never carries a colour of its own. */
  out.set(
    join(catalog, 'mark.imageset', 'mark.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${MARK.viewBox}" width="${(44 * MARK.ratio).toFixed(2)}" height="44">${MARK.paths.map((d) => `<path d="${d}"/>`).join('')}</svg>\n`,
  );
  out.set(join(catalog, 'mark.imageset', 'Contents.json'), imageSet('mark.svg'));

  /* THE NAMES AS SWIFT, so a view asks for `Glyph.decide` and a typo is a compile error rather than an empty well. */
  const cases = glyphs.map(([name]) => `    case ${name.replace(/-([a-z])/g, (_, c) => c.toUpperCase())} = "${assetName(name)}"`);
  out.set(
    join(apple, 'Packages', 'BrainDogKit', 'Sources', 'BrainDogKit', 'Look', 'Glyph.generated.swift'),
    `// GENERATED by apps/apple/tools/icons.mjs from apps/web/src/lib/ui/icons.ts. Do not edit: run the script again.

import SwiftUI

/// The web's glyph set, as template images: each takes the colour of the text it sits in.
public enum Glyph: String, CaseIterable, Sendable {
${cases.join('\n')}

    /// The glyph at the web's 1.75 stroke.
    public var image: Image { Image(rawValue, bundle: .module).renderingMode(.template) }
    /// The same shape at 1.5, for a tab bar, beside the system's own lighter tab glyphs.
    public var tabImage: Image { Image(rawValue + ".tab", bundle: .module).renderingMode(.template) }
}
`,
  );
  return out;
}

async function read(path) {
  try {
    return await readFile(path, 'utf8');
  } catch {
    return null;
  }
}

const wanted = await outputs();
if (argv.includes('--check')) {
  const stale = [];
  for (const [path, text] of wanted) if ((await read(path)) !== text) stale.push(path);
  if (stale.length > 0) {
    console.error(`These are not what icons.ts makes now; run node apps/apple/tools/icons.mjs:\n${stale.map((p) => `  ${p}`).join('\n')}`);
    exit(1);
  }
  console.log(`${wanted.size} glyph files match icons.ts.`);
} else {
  const kept = new Set([...wanted.keys()].map((p) => dirname(p)));
  for (const entry of await readdir(catalog).catch(() => [])) {
    const at = join(catalog, entry);
    if (entry.endsWith('.imageset') && !kept.has(at)) await rm(at, { recursive: true });
  }
  for (const [path, text] of wanted) {
    await mkdir(dirname(path), { recursive: true });
    if ((await read(path)) !== text) await writeFile(path, text);
  }
  console.log(`wrote ${(wanted.size - 4) / 4} glyphs, each at 1.75 and at 1.5 for a tab, and Glyph.generated.swift`);
}
