/**
 * `tell-core.js`: the web's Tell reader, bundled for JavaScriptCore (plan 3.9).
 *
 *   node apps/apple/tools/tell-core.mjs           build it
 *   node apps/apple/tools/tell-core.mjs --check   fail if the committed bundle is not what the web's reader builds now
 *
 * ONE FILE, NO MODULES, NO DOM. The entry is `apps/web/src/lib/tell/native.ts` (the reader and its options), bundled by
 * esbuild as an IIFE that puts `BrainDogTell` on the global object: `readJSON(sentence, optionsJSON)` and
 * `optionsJSON(boot, schemas, today, known)`. JavaScriptCore has no `window`, `document` or `fetch`, and the reader needs
 * none; a module of the web's that touched one at load would throw when `TellCore.swift` evaluates the file, which is
 * where a regression shows.
 *
 * COMMITTED, so the apps build with Xcode alone. `--check` says when the web's reader moved and this was not run.
 */

import { realpathSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { argv, exit } from 'node:process';

const apple = join(import.meta.dirname, '..');
const root = join(apple, '..', '..');
const web = join(root, 'apps', 'web');
const out = join(apple, 'Packages', 'BrainDogKit', 'Sources', 'BrainDogKit', 'Resources', 'tell-core.js');

/* ESBUILD IS THE ONE VITE BRINGS, found from the web app, so the apps add no dependency of their own. */
const require = createRequire(join(root, 'package.json'));
const esbuild = await import(require.resolve('esbuild', { paths: [root, web, realpathSync(join(web, 'node_modules', 'vite'))] }));

const built = await esbuild.build({
  entryPoints: [join(web, 'src', 'lib', 'tell', 'native.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'BrainDogTell',
  platform: 'neutral',
  target: 'safari17',
  mainFields: ['module', 'main'],
  conditions: ['import', 'default'],
  absWorkingDir: web,
  minify: true,
  legalComments: 'none',
  treeShaking: true,
  define: { 'import.meta.env.DEV': 'false', 'import.meta.env.SSR': 'false', __BRAINDOG_ENV__: '""' },
  logLevel: 'warning',
});
const text = `/* GENERATED by apps/apple/tools/tell-core.mjs from apps/web/src/lib/tell/native.ts. Do not edit. */\n${built.outputFiles[0].text}`;

if (argv.includes('--check')) {
  const was = await readFile(out, 'utf8').catch(() => null);
  if (was !== text) {
    console.error('tell-core.js is not what the web reader builds now; run node apps/apple/tools/tell-core.mjs');
    exit(1);
  }
  console.log('tell-core.js matches the web reader.');
} else {
  await writeFile(out, text);
  console.log(`wrote tell-core.js, ${(text.length / 1024).toFixed(0)} KB`);
}
